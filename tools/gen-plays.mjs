// Writes the engine checks' play scripts (tests/native/*.play) from the rules:
// each board is solved by a breadth-first search over src/rules.js moves (the
// shortest solution, as the content's par), and the moves become the peg
// focus keys (←/→ from the focused peg, Enter to lift and drop) or clicks on
// the accessible peg mirror's buttons ("Peg 3: …"). Run after changing the
// rules, the content or the screens: `npm run plays`.
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { solution } from './solve.mjs';
import { getJourneyStage, getLesson } from '../src/content.js';

const OUT = join(new URL('..', import.meta.url).pathname, 'tests', 'native');
mkdirSync(OUT, { recursive: true });

/** Keys from the focused peg to `to` (shortest way round, as ←/→ wrap) and Enter. */
function keysTo(focus, to, n) {
  const out = [];
  const right = (to - focus + n) % n, left = (focus - to + n) % n;
  for (let i = 0; i < Math.min(right, left); i++) out.push(`key ${right <= left ? 'ArrowRight' : 'ArrowLeft'} 1`);
  out.push('key Enter 1', 'frames 20');
  return out;
}
/** A board solved by keys (every `clickEvery`th move by clicking the mirror's buttons instead). */
function solveSteps(rec, clickEvery = 0) {
  const moves = solution(rec);
  const n = rec.pegs.length;
  let focus = 0;
  const lines = [`# ${rec.id}: ${moves.length} moves (par ${rec.par})`];
  moves.forEach((m, i) => {
    if (clickEvery && i % clickEvery === clickEvery - 1) {
      lines.push(`click Peg ${m.from + 1}:`, 'frames 10', `click Peg ${m.to + 1}:`, 'frames 20');
      focus = m.to;
      return;
    }
    lines.push(...keysTo(focus, m.from, n));
    focus = m.from;
    lines.push(...keysTo(focus, m.to, n));
    focus = m.to;
  });
  return lines;
}
const write = (name, header, lines) => writeFileSync(join(OUT, name), [`# Generated by tools/gen-plays.mjs. ${header}`, ...lines, ''].join('\n'));

